import assert from 'node:assert/strict';
import {publicCountrySupply} from '../dist/country-supply-counts.js';
import {acquireCountry,revealCountry} from '../dist/country-piles.js';
const region={available:['a','b'],deck:['hidden-a','hidden-b'],countryPiles:{left:['a','hidden-a','hidden-b'],right:['b']}};
const before=structuredClone(region);
assert.deepEqual(publicCountrySupply(region),[{id:'a',pile:'left',count:3},{id:'b',pile:'right',count:1}]);
assert.deepEqual(region,before);
const redacted={...region,countryPiles:{left:['a',null,null],right:['b']}};
assert.deepEqual(publicCountrySupply(redacted),publicCountrySupply(region));
const guard=values=>new Proxy(values,{get(target,key,receiver){if(/^\d+$/.test(String(key))&&Number(key)>0)throw Error('Read a hidden identity');return Reflect.get(target,key,receiver);}});
assert.equal(publicCountrySupply({...region,countryPiles:{left:guard(region.countryPiles.left),right:guard(region.countryPiles.right)}})[0].count,3);
acquireCountry(region,'a');assert.deepEqual(publicCountrySupply(region).map(x=>x.count),[2,1]);
revealCountry(region);assert.deepEqual(publicCountrySupply(region).map(x=>x.count),[1,2]);
assert.deepEqual(publicCountrySupply({available:['b'],countryPiles:{left:[],right:['b',null]}}),[{id:'b',pile:'right',count:2}]);
assert.deepEqual(publicCountrySupply({available:['a','b'],deck:[null,null]}).map(x=>x.count),[3,1]);
assert.equal(publicCountrySupply({available:['unknown'],countryPiles:{left:['a'],right:[]}})[0].count,null);
assert.equal(publicCountrySupply({available:['a']})[0].count,null);
assert.deepEqual(publicCountrySupply({available:[],deck:[]}),[]);
console.log('Country pile counters passed: public top/length only, redacted parity, reveal/acquire, legacy and unknown states.');
