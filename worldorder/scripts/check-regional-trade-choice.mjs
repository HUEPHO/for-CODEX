import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {createState,applyAction} from '../dist/engine.js';
import {newFlow} from '../dist/flow.js';
import {sequencePreview} from '../dist/card-sequence.js';
import {allocateRegionalExports} from '../dist/regional-trade.js';
import {tradePreview} from '../dist/trade.js';

const cards=JSON.parse(readFileSync(new URL('../dist/cards.json',import.meta.url),'utf8'));
const cap={byRegion:{M:{exports:[2,0,0,2,1,0,0]},P:{exports:[2,0,0,2,1,0,0]}}};
const bonus={minimumRevenue:35};
const exports=[{key:3,quantity:4},{key:0,quantity:2}];
const assigned=allocateRegionalExports(exports,cap,bonus,['M','P']);
assert.deepEqual(assigned,[{key:3,quantity:4,regions:{M:2,P:2}},{key:0,quantity:2,regions:{M:1,P:1}}]);
assert.throws(()=>allocateRegionalExports([{key:3,quantity:2},{key:0,quantity:1}],cap,bonus,['M','P']),/不足/);
assert.throws(()=>allocateRegionalExports(exports,cap,bonus,['M','M']),/不同/);
assert.throws(()=>allocateRegionalExports(exports,cap,{...bonus,regions:['M']},['P']),/允许/);
assert.throws(()=>allocateRegionalExports([{key:0,quantity:3}],cap,{requirements:{0:4}},['M']),/不足/);

let s=createState(cards,{dd:true,wit:true},()=>.5);
for(const p of Object.values(s.players))p.openingChoices=p.assetChoices=p.objectiveChoices=null;
s.current='CN';s.flow=newFlow(['CN','US','EU','RU']);s.phase='行动';s.actionTurns={index:0,completed:{US:0,CN:0,EU:0,RU:0}};
s.players.CN.money=100;s.players.CN.resources=Array(7).fill(8);s.players.CN.assets=['c3dc6bb01a4f1'];s.players.CN.usedAssets=[];
s.players.CN.allies=cards.filter(c=>c.type==='country'&&['M','P'].includes(c.region)).map(c=>c.id);
s=applyAction(s,{type:'startSequenceCard',cardId:'c3dc6bb01a4f1',cover:s.players.CN.hand[0]});
const initial=JSON.stringify(s),sale={exports,imports:[{key:4,players:{US:1}}],rewardRegions:['M','P']};
const quote=sequencePreview(s,sale);assert.equal(JSON.stringify(s),initial);assert.deepEqual(quote.bonusRegions,['M','P']);assert.equal(quote.exportRevenueByRegion.M,35);assert.equal(quote.exportRevenueByRegion.P,35);
assert.throws(()=>applyAction(s,{type:'resolveSequenceStep',exports:[{key:3,quantity:2},{key:0,quantity:1}],rewardRegions:['M','P']}),/不足/);assert.equal(JSON.stringify(s),initial);
s=applyAction(s,{type:'resolveSequenceStep',...sale});assert.equal(s.players.CN.money,160);assert.equal(s.players.CN.resources[3],4);assert.equal(s.players.CN.resources[0],6);
s=JSON.parse(JSON.stringify(s));s=applyAction(s,{type:'resolveSequenceStep',region:'M',slot:'temporary'});s=applyAction(s,{type:'resolveSequenceStep',region:'P',slot:'temporary'});assert.equal(s.players.CN.money,160);assert.equal(s.actionTurns.index,1);
const oldState=JSON.parse(initial),legacy=exports.map(row=>({...row,regions:assigned.find(x=>x.key===row.key).regions}));
assert.deepEqual(sequencePreview(oldState,{exports:legacy}).bonusRegions,['M','P']);
assert.throws(()=>sequencePreview(oldState,{exports}),/分配/);
assert.deepEqual(sequencePreview(oldState,{exports,rewardRegions:[]}).bonusRegions,[]);
assert.throws(()=>tradePreview(oldState,{exports:[],rewardRegions:[]},{name:'普通贸易'}),/奖励地区/);
let energy=createState(cards,{dd:true,wit:true},()=>.5);
for(const p of Object.values(energy.players))p.openingChoices=p.assetChoices=p.objectiveChoices=null;
energy.current='RU';energy.flow=newFlow(['RU','CN','US','EU']);energy.phase='行动';energy.actionTurns={index:0,completed:{US:0,CN:0,EU:0,RU:0}};
Object.assign(energy.players.RU,{money:100,resources:Array(7).fill(8),assets:['cc55c9955c210'],usedAssets:[],allies:['c35627e0bba08']});
energy.regions.S.available=['c72267e12c089'];energy.regions.P.available=['cf04deb0c883b','c99daf8fee754'];
energy=applyAction(energy,{type:'startSequenceCard',cardId:'cc55c9955c210',cover:energy.players.RU.hand[0]});
energy=applyAction(energy,{type:'resolveSequenceStep',regions:['S','P']});
assert.deepEqual(sequencePreview(energy,{exports:[{key:0,quantity:8}],rewardRegions:['S','P']}).bonusRegions,['S','P']);
assert.throws(()=>sequencePreview(energy,{exports:[{key:0,quantity:7}],rewardRegions:['S','P']}),/不足/);
assert.throws(()=>sequencePreview(energy,{exports:[{key:0,quantity:8}],rewardRegions:['E']}),/允许/);
console.log('Regional trade choice passed: totals before destinations, joint thresholds without double counting, eligibility and legacy validation, atomic payment, saved reward steps and no duplicate settlement.');
