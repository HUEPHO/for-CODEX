import fs from 'node:fs';
const cards=JSON.parse(fs.readFileSync(new URL('../dist/cards.json',import.meta.url)));
const data={};
for(const c of cards){
 if(['starter','ability'].includes(c.type)){
  const m=/^(\d)(\d)([CDT])(\d)?$/.exec(c.notes);
  if(!m||(c.type==='ability')!==!!m[4])throw Error('Unrecognized research metadata: '+c.id);
  // Verified against all 24 distinct bonus/cost patterns. TTS 40C7 encodes 10 money, not zero.
  data[c.id]={research:Number(m[1]),bonus:{type:{C:'money',D:'diplomacy',T:'armies'}[m[3]],amount:Number(m[2])||(m[3]==='C'?10:0)},...(m[4]?{cost:Number(m[4])}:{})};
 }else if(['country','startingCountry'].includes(c.type)){
  const m=/-(\d)-[MECNASP]$/.exec(c.notes);if(!m)throw Error('Unrecognized country value: '+c.id);
  const fields=/^(.*)-(\d+)-([AERC]*)-([AERC]*)-(\d)-([MECNASP])$/.exec(c.notes);if(!fields)throw Error('Unrecognized country flags: '+c.id);
  const powers=flags=>[...flags].map(letter=>({A:'US',E:'EU',R:'RU',C:'CN'}[letter]));
  data[c.id]={countryValue:Number(m[1]),region:c.region,investmentCost:Number(fields[2]),countryName:fields[1],starting:c.type==='startingCountry',blockedPowers:powers(fields[3]),basePowers:powers(fields[4])};
 }
}
if(Object.keys(data).length!==215)throw Error('Unexpected data coverage');
fs.writeFileSync(new URL('../dist/research-data.js',import.meta.url),'// Generated by scripts/import-research.mjs from the supplied TTS metadata.\nexport const RESEARCH_DATA = Object.freeze('+JSON.stringify(data,null,2)+');\n');
console.log('Saved verified research fields for 122 ability cards and 93 country cards.');
